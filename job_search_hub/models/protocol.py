"""Minimum interface for an eventual explicitly configured model provider."""

from typing import Any, Protocol


class ModelClient(Protocol):
    def list_model_ids(self) -> list[str]: ...
    def chat(self, *, model: str, messages: list[dict[str, str]], **kwargs: Any) -> str: ...
    def chat_json(self, *, model: str, messages: list[dict[str, str]], **kwargs: Any) -> dict: ...
    def embed(self, *, model: str, inputs: list[str], **kwargs: Any) -> list[list[float]]: ...
    def close(self) -> None: ...
